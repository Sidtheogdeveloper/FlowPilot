"""Train real LoRA weights on CPU and measure held-out before/after generations.

Run from application root: python -m training.train_adapter --model-cache <snapshot>
No provider calls, no executable code generated by the model, no paid resources.
"""
import argparse,hashlib,json,random,time
from pathlib import Path
import torch
from transformers import AutoModelForCausalLM,AutoTokenizer
from app.intent_schema import Intent,check_context,BASE_OPERATIONS
from training.lora import attach_lora,adapter_state

ROOT=Path(__file__).resolve().parent
def read_rows(path):return [json.loads(line) for line in path.read_text(encoding='utf-8').splitlines() if line]
def fingerprint(path):return hashlib.sha256(path.read_bytes()).hexdigest()

def evaluate(model,tokenizer,rows,path,label):
    results=[];model.eval()
    for row in rows:
        start=time.monotonic()
        prompt=tokenizer.apply_chat_template(row['messages'],tokenize=False,add_generation_prompt=True)
        encoded=tokenizer(prompt,return_tensors='pt')
        with torch.inference_mode():output=model.generate(**encoded,max_new_tokens=192,do_sample=False,pad_token_id=tokenizer.eos_token_id)
        content=tokenizer.decode(output[0,encoded['input_ids'].shape[1]:],skip_special_tokens=True)
        valid=False;exact=False;error=None
        try:
            raw=json.loads(content.strip())
            intent=Intent.model_validate(raw);check_context(intent,row['context'])
            if intent.operations!=BASE_OPERATIONS:raise ValueError('Operation list changed')
            if intent.iqr_multiplier!=row['target']['iqr_multiplier']:raise ValueError('IQR value changed')
            valid=True;exact=raw==row['target']
        except (ValueError,TypeError) as exc:error=str(exc)
        results.append({'id':row['id'],'output':content,'schema_and_constraints_valid':valid,'exact_target':exact,'error':error,'seconds':round(time.monotonic()-start,3)})
        path.write_text(json.dumps({'label':label,'results':results},indent=2),encoding='utf-8')
        print(json.dumps({'evaluation':label,'id':row['id'],'valid':valid,'exact':exact,'seconds':results[-1]['seconds']}),flush=True)
    return {'count':len(results),'valid':sum(r['schema_and_constraints_valid'] for r in results),'exact':sum(r['exact_target'] for r in results),'total_seconds':round(sum(r['seconds'] for r in results),3)}

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--model-cache',required=True);parser.add_argument('--steps',type=int,default=80);parser.add_argument('--threads',type=int,default=8);parser.add_argument('--learning-rate',type=float,default=.001);parser.add_argument('--output',type=Path,default=ROOT/'artifacts'/'intent-lora');parser.add_argument('--skip-baseline',action='store_true');args=parser.parse_args()
    torch.set_num_threads(args.threads);torch.manual_seed(20261008);random.seed(20261008)
    args.output.mkdir(parents=True,exist_ok=True)
    train_path=ROOT/'train.jsonl';heldout_path=ROOT/'heldout.jsonl';rows=read_rows(train_path);heldout=read_rows(heldout_path)
    tokenizer=AutoTokenizer.from_pretrained(args.model_cache,local_files_only=True)
    model=AutoModelForCausalLM.from_pretrained(args.model_cache,local_files_only=True,dtype=torch.float32,attn_implementation='sdpa').to('cpu')
    before=evaluate(model,tokenizer,heldout,args.output/'before.json','frozen-base') if not args.skip_baseline else None
    targets=attach_lora(model,rank=8,alpha=16)
    parameters=[p for p in model.parameters() if p.requires_grad];optimizer=torch.optim.AdamW(parameters,lr=args.learning_rate,weight_decay=0)
    count=sum(p.numel() for p in parameters)
    print(json.dumps({'trainable_parameters':count,'total_parameters':sum(p.numel() for p in model.parameters()),'targets':len(targets),'threads':args.threads}),flush=True)
    encoded_rows=[]
    for row in rows:
        prompt=tokenizer.apply_chat_template(row['messages'],tokenize=False,add_generation_prompt=True)
        full=tokenizer.apply_chat_template(row['messages']+[{'role':'assistant','content':json.dumps(row['target'],separators=(',',':'))}],tokenize=False,add_generation_prompt=False)
        encoded=tokenizer(full,return_tensors='pt');labels=encoded['input_ids'].clone();labels[:,:len(tokenizer(prompt)['input_ids'])]=-100
        encoded_rows.append((encoded,labels))
    model.train();model.config.use_cache=False
    order=list(range(len(rows)));random.shuffle(order);losses=[];started=time.monotonic()
    for step in range(args.steps):
        if step and step%len(order)==0:random.shuffle(order)
        inputs,labels=encoded_rows[order[step%len(order)]]
        optimizer.zero_grad(set_to_none=True)
        loss=model(**inputs,labels=labels).loss
        if not torch.isfinite(loss):raise ValueError('Non-finite training loss')
        loss.backward();torch.nn.utils.clip_grad_norm_(parameters,1);optimizer.step()
        losses.append(float(loss.detach()))
        if step<3 or (step+1)%10==0:print(json.dumps({'step':step+1,'loss':round(losses[-1],5),'elapsed_seconds':round(time.monotonic()-started,2)}),flush=True)
    elapsed=time.monotonic()-started
    state=adapter_state(model);torch.save(state,args.output/'adapter.pt')
    nonzero=sum(float(value.abs().sum()) for name,value in state.items() if name.endswith('lora_B'))
    if nonzero==0:raise ValueError('No adapter updates occurred')
    metadata={'base_model':'Qwen/Qwen2.5-0.5B-Instruct','base_snapshot':Path(args.model_cache).name,'method':'manual attention q_proj/v_proj LoRA','rank':8,'alpha':16,'trainable_parameters':count,'seed':20261008,'steps':args.steps,'learning_rate':args.learning_rate,'threads':args.threads,'training_seconds':round(elapsed,3),'losses':losses,'nonzero_B_absolute_sum':nonzero,'train_sha256':fingerprint(train_path),'heldout_sha256':fingerprint(heldout_path),'adapter_sha256':fingerprint(args.output/'adapter.pt'),'training_examples':len(rows),'training_examples_used_unique':min(len(rows),args.steps),'heldout_examples':len(heldout),'torch_version':torch.__version__,'tokenizer_sha256':fingerprint(Path(args.model_cache)/'tokenizer.json')}
    (args.output/'adapter_config.json').write_text(json.dumps(metadata,indent=2),encoding='utf-8')
    model.config.use_cache=True
    after=evaluate(model,tokenizer,heldout,args.output/'after.json','trained-lora')
    # Tiny synthetic evaluation cannot certify generalization. Activation is opt-in
    # and requires no regression plus a measured strict exact-output improvement.
    recommended=bool(before and after['valid']>=before['valid'] and after['exact']>before['exact'])
    report={'before':before,'after':after,'activation_recommended_on_this_pilot':recommended,'adapter_sha256':metadata['adapter_sha256'],'training_seconds':round(elapsed,3),'trainable_parameters':count,'steps':args.steps,'dataset_note':'Reviewed synthetic schema-adherence labels; held-out wording/months/products. Not a financial reasoning benchmark.'}
    (args.output/'evaluation.json').write_text(json.dumps(report,indent=2),encoding='utf-8')
    print(json.dumps(report),flush=True)
if __name__=='__main__':main()
